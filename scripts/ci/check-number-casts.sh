# check-number-casts.sh — the numeric-argument rule (#228, closed out by #247).
#
# A JSON number reaches the code as float64. The one module that turns it into a
# validated whole number is internal/numarg, and the use-case layer must only
# receive values that module has already checked.
#
#   1. internal/app holds no float64 at all. A use case takes int or int64, and
#      the adapter in internal/operation converts with numarg.
#   2. internal/operation may still declare float64 argument fields (the decode
#      boundary, docs/agents/adding-a-tool.md), but the number of float64 mentions
#      per file may not grow. scripts/ci/number-float64-baseline.txt records the
#      current counts; a migration lowers its entry, and a new float64 in a file
#      fails here. Run with --write after a migration lowers counts, never to
#      raise one.
#
# Usage: check-number-casts.sh [--write]
# Exit 0 when clean, 1 on a violation.

set -eu

cd "$(dirname "$0")/../.."

baseline=scripts/ci/number-float64-baseline.txt

current() {
	find internal/operation -name '*.go' ! -name '*_test.go' | sort | while read -r f; do
		n=$(grep -o 'float64' "$f" | wc -l | tr -d ' ')
		if [ "$n" -gt 0 ]; then echo "$n $f"; fi
	done
}

if [ "${1:-}" = "--write" ]; then
	{
		echo "# float64 mentions per non-test file under internal/operation (count path)."
		echo "# Generated by scripts/ci/check-number-casts.sh --write. Counts may only fall."
		current
	} >"$baseline"
	echo "wrote $baseline"
	exit 0
fi

status=0

app=$(find internal/app -name '*.go' ! -name '*_test.go' -exec grep -ln 'float64' {} + 2>/dev/null || true)
if [ -n "$app" ]; then
	echo "error: float64 in the use-case layer (internal/app). Take int or int64 and convert in the adapter with internal/numarg:" >&2
	echo "$app" | sed 's/^/  /' >&2
	status=1
fi

over=$(current | awk '
	NR == FNR { if ($0 !~ /^#/ && NF == 2) base[$2] = $1; next }
	{ b = ($2 in base) ? base[$2] : 0; if ($1 > b) printf "  %s: %s float64 mentions, baseline %s\n", $2, $1, b }
' "$baseline" -)
if [ -n "$over" ]; then
	echo "error: float64 mentions grew under internal/operation. Convert the value with internal/numarg, or justify the field and rerun with --write only if the count fell:" >&2
	echo "$over" >&2
	status=1
fi

exit $status
